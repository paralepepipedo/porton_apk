-- que suba el administrador. El aviso unico de siempre (porton_avisos,
-- la franja naranja) queda intacto y sigue funcionando igual.

create table if not exists porton_anuncios (
  id bigint generated by default as identity primary key,
  texto text not null,
  estilo text not null default 'oficial'
    check (estilo in ('agua','fiesta','oficial','emergencia','jardin','elegante','informativo','personalizado')),
  imagen_url text,
  orden integer not null default 0,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create index if not exists porton_anuncios_orden_idx on porton_anuncios (orden);

insert into storage.buckets (id, name, public)
values ('anuncios', 'anuncios', true)
on conflict (id) do nothing;
